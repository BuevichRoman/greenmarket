"""Какой коммит развёрнут на этой машине.

Нужно, чтобы снаружи можно было спросить у прода его версию и сравнить с
`origin/main`, не заходя на сервер. Поводом послужил случай 06.08.2026: деплой
упал на стороне GitHub («Failed to resolve action download info»), прод сутки
простоял позади main, и заметили это случайно — упавший деплой о себе не
сообщает.

Через SSH такую проверку сделать нельзя: ключ CI заперт в `authorized_keys`
через `command="bash /opt/greenmarket/deploy.sh"`, поэтому любой присланный
скрипт превращается в деплой. Ограничение правильное и снимать его незачем —
проще, чтобы приложение само отдавало свою версию.

Файл пишет деплой (`ci/deploy-impl.sh`), он не в git. Путь выводится из
расположения пакета, а не из конфигурации: переменная окружения означала бы
ручной шаг на проде, а он тут ни к чему.
"""

import re
from pathlib import Path

DEPLOYED_SHA_FILE = Path(__file__).resolve().parents[2] / "DEPLOYED_SHA"

_SHA = re.compile(r"^[0-9a-f]{40}$")


def read_deployed_commit() -> str | None:
    """Полный SHA развёрнутого коммита, либо `None`.

    `None` — это и «файла нет» (локальная разработка, окружение поднято не
    деплоем), и «в файле не хеш». Мусор специально не отдаётся наружу: иначе
    проверка расхождения сравнивала бы `origin/main` с чем попало и падала бы
    каждый день по причине, не имеющей отношения к деплою.
    """
    try:
        value = DEPLOYED_SHA_FILE.read_text().strip()
    except OSError:
        return None
    return value if _SHA.match(value) else None
