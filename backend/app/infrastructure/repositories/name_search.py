"""Поиск по наименованию в каталоге покупателя (REST_API.md, параметр `search`).

Одно место на оба каталога — общий и каталог продавца: правила совпадения
покупатель считает одинаковыми, и расходиться они не должны.
"""

# Обратный слэш экранируется первым: иначе он повторно экранировал бы уже
# подставленные `\%` и `\_`.
_LIKE_SPECIALS = str.maketrans({"\\": "\\\\", "%": "\\%", "_": "\\_"})

LIKE_ESCAPE = "\\"


def name_search_patterns(search: str | None) -> list[str]:
    """Поисковый запрос → LIKE-шаблоны, каждый из которых обязан найтись.

    Слова сопоставляются независимо и в любом порядке: «вяленая клюква» должно
    находить «Клюкву вяленую». Порядок слов в справочнике покупателю не виден,
    и угадывать его он не обязан. Разбиение по `split()` заодно снимает краевые
    и повторные пробелы — интерфейс присылает их сам, вставкой из буфера.

    `%` и `_` экранируются и означают сами себя. Инъекции здесь нет — запрос
    параметризован, — но необработанный `%` возвращал весь каталог, а на фронте
    это неотличимо от применившегося поиска.

    Пустой список означает «поиск не задан», а не «ничего не найдено»: пустой
    и пробельный запрос — это отсутствие фильтра.
    """
    if not search:
        return []
    return [f"%{word.translate(_LIKE_SPECIALS)}%" for word in search.split()]
