-- Migration : 020_alter_seller_products_add_concurrency.sql
-- Purpose   : Две колонки под безопасную двухстороннюю синхронизацию каталога
--             (ТЗ «Безопасная двухсторонняя синхронизация», разделы 17 и 21):
--             `version` — токен оптимистической блокировки, `idempotency_key`
--             — ключ идемпотентности создания позиции.
-- Note      : `version`, а не `updated_at` в роли токена. На проде `sql_mode`
--             пуст и `updated_at` объявлен как DATETIME секундной точности:
--             две правки в одну секунду неразличимы, и гонка, ради которой
--             всё и делается, прошла бы незамеченной. Целое число растёт при
--             каждом изменении строки и от точности часов не зависит.
-- Note      : DEFAULT 1 закрывает существующие строки: у всех позиций,
--             заведённых до этой миграции, версия становится первой, и
--             первое же изменение через API сделает её второй.
-- Note      : UNIQUE (seller_id, idempotency_key), а не UNIQUE
--             (idempotency_key): ключ генерирует клиент в своей книге, и
--             совпадение ключей у двух разных продавцов — их частное дело, а
--             не конфликт. Ровно та же причина, что у
--             uk_SellerProduct_seller_sku (миграция 018).
-- Note      : MySQL допускает повторяющиеся NULL в UNIQUE-индексе, поэтому
--             позиции без ключа (заведённые из книги или до этой миграции)
--             ограничение не задевает.
-- DBMS      : MySQL Community Server 8.0.16+

ALTER TABLE SellerProduct
    ADD COLUMN version INT NOT NULL DEFAULT 1
        COMMENT 'Токен оптимистической блокировки: растёт при каждом изменении строки',
    ADD COLUMN idempotency_key VARCHAR(64) NULL
        COMMENT 'Ключ идемпотентности создания, генерируется клиентом и живёт в книге',
    ADD CONSTRAINT uk_SellerProduct_idempotency_key UNIQUE (seller_id, idempotency_key);
